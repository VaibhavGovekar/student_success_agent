
"""
Reusable Student Success Agent cycle.

Flow:
Observe tasks -> Validate -> Recommend -> Plan -> Validate
-> Replan if needed -> Return structured results.
"""

from agent_workflow import (
    load_student_data,
    create_study_schedule,
    validate_schedule,
    replan_schedule,
    get_missed_deadline_warnings,
    validate_task_data,
)
from gemini_recommendations import (
    generate_recommendations as generate_gemini_recommendations,
)
from mock_ai_engine import (
    generate_recommendations as generate_mock_recommendations,
)
from priority_engine import rank_tasks


def _fallback_reason(error):
    message = str(error).lower()
    if "503" in message or "unavailable" in message or "high demand" in message:
        return "Gemini is temporarily busy. Try again in a little while."
    if "429" in message or "resource_exhausted" in message or "quota" in message:
        return "Gemini rate limit or quota reached. Check your Google AI Studio usage and retry later."
    if "api_key_invalid" in message or "unauthenticated" in message or "permission_denied" in message:
        return "Gemini rejected the key or project access. Check GEMINI_API_KEY and the Google AI project."
    if "gemini_api_key" in message and "missing" in message:
        return "GEMINI_API_KEY is missing from backend/.env."
    return f"Gemini request failed ({type(error).__name__})."


def run_agent_cycle(student_data=None, available_hours=None):
    """
    Run one complete agent cycle and return structured results.

    Pass student_data and available_hours for testing or API use.
    If omitted, load tasks.json and use its available hours.
    """

    # 1. OBSERVE: load and validate student data.
    if student_data is None:
        student_data = load_student_data()

    if not isinstance(student_data, dict):
        raise ValueError("Student data must be a dictionary.")

    tasks = student_data.get("tasks")

    if not isinstance(tasks, list):
        raise ValueError("'tasks' must be a list.")

    # Check that each task is a dictionary and has required fields.
    required_fields = [
        "title",
        "due_date",
        "duration_hours",
        "status",
    ]

    for index, task in enumerate(tasks):
        if not isinstance(task, dict):
            raise ValueError(
                f"Task at index {index} must be a dictionary."
            )

        for field in required_fields:
            if field not in task:
                raise ValueError(
                    f"Task at index {index} is missing required field: "
                    f"'{field}'."
                )

    # Validate field values before processing tasks.
    task_errors = validate_task_data(tasks)

    if task_errors:
        raise ValueError(
            "Invalid task data: " + " ".join(task_errors)
        )

    # Report overdue tasks separately from validation errors.
    missed_deadline_warnings = get_missed_deadline_warnings(tasks)

    if available_hours is None:
        available_hours = student_data.get("available_hours_per_day")

    if (
        isinstance(available_hours, bool)
        or not isinstance(available_hours, int)
        or available_hours <= 0
    ):
        raise ValueError(
            "Available hours must be a positive integer."
        )

    # 2. RECOMMEND: generate structured mock recommendations.
    recommendation_fallback_reason = None
    try:
        recommendations = generate_gemini_recommendations(tasks)
        recommendation_source = "gemini"
        print("Recommendations generated by Gemini.")

    except Exception as exc:
        recommendation_fallback_reason = _fallback_reason(exc)
        print(f"Gemini unavailable; using mock recommendations: {recommendation_fallback_reason}")
        recommendations = generate_mock_recommendations(tasks)
        recommendation_source = "mock_rules"
  
    # 3. PLAN: rank tasks and create an initial schedule.
    ranked_tasks = rank_tasks(
        tasks,
        recommendations=recommendations,
    )

    schedule = create_study_schedule(
        ranked_tasks,
        available_hours,
    )

    # 4. EVALUATE: validate the initial schedule.
    errors = validate_schedule(
        schedule,
        available_hours,
        tasks=tasks,
    )

    initial_errors = list(errors)
    replanning_attempted = False

    # 5. REPLAN: retry using the existing replanning engine.
    if errors:
        replanning_attempted = True

        revised_schedule, revised_errors = replan_schedule(
            tasks,
            available_hours,
        )

        schedule = revised_schedule
        errors = revised_errors

    # 6. RETURN: provide structured results to the caller.
    recovery_schedule = bool(missed_deadline_warnings)
    return {
        "student_id": student_data.get("student_id"),
        "available_hours_per_day": available_hours,
        "missed_deadline_warnings": missed_deadline_warnings,
        "recommendations": recommendations,
        "ranked_tasks": ranked_tasks,
        "schedule": schedule,
        "initial_validation_errors": initial_errors,
        "validation_errors": errors,
        "replanning_attempted": replanning_attempted,
        "success": len(errors) == 0,
                "schedule_status": (
            "valid" if not errors else "invalid"
        ),
        "recovery_schedule": recovery_schedule,
        "schedule_type": (
            "recovery" if recovery_schedule else "regular"
        ),
        "recommendation_source": recommendation_source,
        "recommendation_fallback_reason": recommendation_fallback_reason,
    }


if __name__ == "__main__":
    result = run_agent_cycle()

    print("STUDENT SUCCESS AGENT - COMPLETE CYCLE")
    print("=" * 45)
    print("Student ID:", result["student_id"])
    print("Schedule status:", result["schedule_status"])
    print("Schedule type:", result["schedule_type"])
    print("Replanning attempted:", result["replanning_attempted"])

    print("\nRECOMMENDATIONS")
    for item in result["recommendations"]:
        print(
            f"- {item['task_title']}: {item['priority']} "
            f"({item['priority_reason']})"
        )

    print("\nFINAL SCHEDULE")
    for item in result["schedule"]:
        print(
            f"- {item['title']}: "
            f"{item['start_hour']}:00-{item['end_hour']}:00 "
            f"on {item['scheduled_date']}"
        )

    if result["validation_errors"]:
        print("\nVALIDATION ERRORS")
        for error in result["validation_errors"]:
            print("-", error)
    else:
        print("\nSCHEDULE VALID: All checks passed.")
